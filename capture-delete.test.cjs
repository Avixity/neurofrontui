const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const path = require('node:path')
const os = require('node:os')
const url = process.env.NEUROFRONT_URL || 'http://127.0.0.1:5183'

;(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
  try {
    const context = await browser.newContext({ viewport: { width: 1366, height: 900 } })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.route('**/api/account-config', route => route.fulfill({ json: { configured: false } }))
    await page.route('**/api/assistant', route => route.fulfill({ status: 503, json: { error: { code: 'unavailable' } } }))
    await page.goto(url)
    await page.waitForFunction(() => window.NeuroFrontHistory && document.body.classList.contains('is-ready'))
    await page.evaluate(() => {
      const samples = Array.from({ length: 300 }, (_, i) => 10 + Math.sin(i / 3))
      const baseline = { samples: Array.from({ length: 400 }, (_, i) => 8 + Math.sin(i / 4)), createdAt: '2026-10-01T10:00:00.000Z', durationMs: 20000, sampleIntervalMs: 50, unit: 'uV', calculationVersion: 'neurofront-legacy-1', mean: 8, rms: 8.1, stdDev: 0.7, peakToPeak: 2, derivativeMean: 0.1 }
      window.fixtureCapture = { id: 'delete-test-1', schemaVersion: 1, startedAt: '2026-11-01T10:00:00.000Z', completedAt: '2026-11-01T10:00:15.000Z', durationMs: 15000, sampleIntervalMs: 50, unit: 'uV', samples, axisMin: 6, axisMax: 12, stress: { score: 42, label: 'Balanced' }, summary: { average: 10, peak: 11, minimum: 9, activityLabel: 'Stable' }, baseline, calculationVersion: 'neurofront-legacy-1', device: { name: 'NeuroFront', serviceUuid: SERVICE_UUID, characteristicUuid: CHAR_UUID } }
      for (let i = 1; i <= 3; i++) NeuroFrontHistory.record({ ...fixtureCapture, id: 'delete-test-' + i, completedAt: `2026-11-01T10:0${i}:15.000Z` })
    })
    await page.waitForFunction(() => document.querySelectorAll('.history-delete-button').length === 3 && !document.getElementById('historyStatus').textContent)
    const remove = id => page.locator(`[data-delete-capture-id="${id}"]`)
    const before = await page.evaluate(() => JSON.stringify({ baseline: state.baseline, saved: state.savedBaseline, graph: state.displayBuffer, measurement: state.measurement, export: state.exportSnapshot }))
    await remove('delete-test-1').click()
    assert.equal(await page.locator('#captureDeleteDialog').evaluate(el => el.open), true)
    assert.equal(await page.evaluate(() => document.activeElement.id), 'captureDeleteCancel')
    await page.keyboard.press('Escape')
    assert.equal(await remove('delete-test-1').count(), 1)
    assert.equal(await page.evaluate(() => document.activeElement.dataset.deleteCaptureId), 'delete-test-1')
    await remove('delete-test-1').click()
    await page.locator('#captureDeleteCancel').click()
    assert.equal(await remove('delete-test-1').count(), 1)
    await remove('delete-test-1').click()
    await page.locator('#captureDeleteConfirm').click()
    await page.waitForFunction(() => !document.querySelector('[data-delete-capture-id="delete-test-1"]'))
    assert.equal(await page.evaluate(() => JSON.stringify({ baseline: state.baseline, saved: state.savedBaseline, graph: state.displayBuffer, measurement: state.measurement, export: state.exportSnapshot })), before)
    await page.evaluate(() => NeuroFrontHistory.record(fixtureCapture))
    assert.equal(await remove('delete-test-1').count(), 0)
    await page.reload()
    await page.waitForFunction(() => document.querySelectorAll('.history-delete-button').length === 2)
    assert.equal(await remove('delete-test-1').count(), 0)
    // A failed IndexedDB delete keeps the capture and offers another attempt.
    await page.evaluate(() => { window.originalDelete = IDBObjectStore.prototype.delete; IDBObjectStore.prototype.delete = function(...args) { if (this.name === 'captures') throw new DOMException('Simulated storage failure', 'UnknownError'); return originalDelete.apply(this, args) } })
    await remove('delete-test-2').click()
    await page.locator('#captureDeleteConfirm').click()
    await page.waitForFunction(() => document.getElementById('captureDeleteStatus').textContent.includes('Could not delete'))
    assert.equal(await remove('delete-test-2').count(), 1)
    assert.equal(await page.locator('#captureDeleteConfirm').isEnabled(), true)
    await page.evaluate(() => { IDBObjectStore.prototype.delete = originalDelete })
    await page.locator('#captureDeleteConfirm').click()
    await page.waitForFunction(() => !document.querySelector('[data-delete-capture-id="delete-test-2"]'))
    // Delete also works from details without changing the current results.
    await page.locator('[data-capture-id="delete-test-3"]').click()
    await page.locator('#captureDelete').click()
    await page.keyboard.press('Escape')
    assert.equal(await page.locator('#captureDialog').evaluate(el => el.open), true)
    assert.equal(await page.evaluate(() => document.activeElement.id), 'captureDelete')
    await page.locator('#captureClose').click()
    for (const locale of ['en', 'hi', 'mr', 'bn', 'ta', 'te', 'kn', 'ml', 'gu', 'pa', 'or', 'as', 'ur']) {
      await page.evaluate(locale => NeuroFrontI18n.select(locale), locale)
      await remove('delete-test-3').click()
      assert.equal(await page.locator('#captureDeleteTitle').textContent(), await page.evaluate(locale => NEUROFRONT_TRANSLATIONS[locale]['history.deleteTitle'], locale))
      await page.keyboard.press('Escape')
    }
    await page.evaluate(() => NeuroFrontI18n.select('en'))
    for (const size of [{ width: 1366, height: 900 }, { width: 390, height: 844 }, { width: 320, height: 740 }]) {
      await page.setViewportSize(size)
      await remove('delete-test-3').scrollIntoViewIfNeeded()
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      if (size.width !== 320) await page.screenshot({ path: path.join(os.tmpdir(), `neurofront-delete-${size.width}.png`) })
      await remove('delete-test-3').click()
      assert.ok(await page.locator('#captureDeleteDialog').evaluate(el => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.bottom <= innerHeight }))
      for (let i = 0; i < 4; i++) { await page.keyboard.press('Tab'); assert.ok(await page.evaluate(() => document.getElementById('captureDeleteDialog').contains(document.activeElement))) }
      await page.keyboard.press('Escape')
    }
    await page.locator('[data-capture-id="delete-test-3"]').click()
    await page.locator('#captureExplain').click()
    await page.waitForFunction(() => NeuroFrontAssistant.getSnapshot().messages.some(message => message.status === 'failed'))
    const presetText = await page.locator('.assistant-message.preset').textContent()
    assert.equal(await page.evaluate(() => NeuroFrontAssistant.getSnapshot().capture_id), 'delete-test-3')
    await page.locator('#assistantClose').click()
    await page.locator('[data-capture-id="delete-test-3"]').click()
    await page.locator('#captureDelete').click()
    await page.locator('#captureDeleteConfirm').click()
    await page.waitForFunction(() => !document.getElementById('captureDialog').open && !document.getElementById('captureDeleteDialog').open && !document.getElementById('historyEmpty').hidden)
    assert.equal(await page.evaluate(() => NeuroFrontAssistant.getSnapshot().capture_id), null)
    assert.ok(await page.evaluate(() => NeuroFrontAssistant.getSnapshot().messages.every(message => !message.captureId && !message.retryJob)))
    assert.equal(await page.locator('.assistant-message.preset').textContent(), presetText)
    await page.reload()
    await page.waitForFunction(() => !document.getElementById('historyEmpty').hidden)
    assert.equal(await page.locator('.history-delete-button').count(), 0)
    assert.deepEqual(errors, [])
    console.log(JSON.stringify({ simulatedCaptures: true, guestDeleteAndRefresh: true, cancelAndEscape: true, failureAndRetry: true, duplicateHookIgnored: true, baselineAndCurrentResultsUnchanged: true, detailsPopup: true, languages: 13, viewports: [1366, 390, 320], errors }))
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
